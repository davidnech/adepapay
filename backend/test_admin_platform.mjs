// Isolated PostgreSQL tests. No live tickets, settings or customer data are changed.
import { PGlite } from '@electric-sql/pglite'
import { readFile } from 'node:fs/promises'
import { randomUUID } from 'node:crypto'
import assert from 'node:assert/strict'

const db = new PGlite(), customer = randomUUID(), other = randomUUID()
const query = async (sql, args = []) => (await db.query(sql, args)).rows
const rpc = async (name, args) => (await query(`select public.${name}(${args.map((_, index) => `$${index + 1}`).join(',')}) as value`, args))[0].value
const create = (id = randomUUID(), body = 'Please check my receipt') => rpc('support_create_ticket', [id, customer, 'user@example.test', 'Real User', 'Customer', 'Payment question', 'Payments', body])
const update = (ticket, revision, body, status = null, user = null, id = randomUUID()) => rpc('support_update_ticket', [ticket, id, user, user ? 'user@example.test' : 'admin@example.test', body, revision, status])
const save = (values, revision) => rpc('admin_save_platform_settings', [values, revision, 'admin@example.test'])
try {
  await db.exec("create schema auth; create table auth.users(id uuid primary key,raw_app_meta_data jsonb default '{}',raw_user_meta_data jsonb default '{}',updated_at timestamptz); create role anon; create role authenticated; create role service_role bypassrls;")
  const setup = await readFile(new URL('./setup_database.sql', import.meta.url), 'utf8')
  await db.exec(setup)
  await db.exec(setup)
  for (const id of [customer, other]) await query('insert into auth.users(id) values($1)', [id])
  await db.exec('set role authenticated')
  for (const table of ['platform_settings', 'support_tickets', 'support_messages', 'platform_admin_events', 'admin_notification_reads']) await assert.rejects(() => query(`select * from ${table}`), /permission denied/)
  await assert.rejects(() => save({}, 0), /permission denied/)
  await assert.rejects(() => create(), /permission denied/)
  await db.exec('set role service_role')
  await assert.rejects(() => query("update platform_settings set values='{}'"), /permission denied/)
  const config = await save({ supportEnabled: true, platformName: 'Stored Name' }, 0)
  assert.equal(config.revision, 1)
  assert.equal(config.updated_by, 'admin@example.test')
  await assert.rejects(() => save({}, 0), /Settings changed/)
  // An event failure rolls back the configuration revision and values together.
  await db.exec("reset role; create function reject_admin_event() returns trigger language plpgsql as $$ begin raise exception 'forced audit failure'; end $$; create trigger reject_admin_event before insert on platform_admin_events for each row execute function reject_admin_event(); set role service_role;")
  await assert.rejects(() => save({ supportEnabled: false }, 1), /forced audit failure/)
  assert.equal((await query('select revision from platform_settings'))[0].revision, 1)
  await db.exec('reset role; drop trigger reject_admin_event on platform_admin_events; set role service_role;')
  const id = randomUUID(), ticket = await create(id)
  assert.equal(ticket.user_id, customer)
  assert.equal(ticket.status, 'Open')
  assert.equal((await create(id)).id, id)
  assert.equal((await query('select * from support_messages')).length, 1)
  await assert.rejects(() => create(id, 'Different body'), /identifier already used/)
  await assert.rejects(() => update(id, 1, 'Read another ticket', null, other), /not found/)
  await assert.rejects(() => update(id, 1, 'User resolution', 'Resolved', customer), /Only administrators/)
  const replyId = randomUUID()
  const replied = await update(id, 1, 'We are checking your receipt', 'In Progress', null, replyId)
  assert.equal(replied.revision, 2)
  assert.equal(replied.status, 'In Progress')
  assert.equal((await update(id, 1, 'We are checking your receipt', 'In Progress', null, replyId)).revision, 2)
  assert.equal((await query('select * from support_messages')).length, 2)
  await assert.rejects(() => update(id, 1, 'Stale overwrite', 'Closed'), /changed/)
  await assert.rejects(() => update(id, 2, 'Different retry', null, null, replyId), /identifier already used/)
  assert.equal((await update(id, 2, null, 'Resolved')).status, 'Resolved')
  const reopened = await update(id, 3, 'I still need help', null, customer)
  assert.equal(reopened.status, 'Open')
  assert.equal(reopened.revision, 4)
  // Reply insertion and status changes also roll back on audit failure.
  await db.exec('reset role; create trigger reject_admin_event before insert on platform_admin_events for each row execute function reject_admin_event(); set role service_role;')
  await assert.rejects(() => update(id, 4, 'Unsaved reply', 'Closed'), /forced audit failure/)
  assert.equal((await query('select revision from support_tickets where id=$1', [id]))[0].revision, 4)
  assert.equal((await query('select * from support_messages')).length, 3)
  await db.exec('reset role; drop trigger reject_admin_event on platform_admin_events; set role service_role;')
  const paused = await save({ supportEnabled: false }, 1)
  assert.equal(paused.revision, 2)
  await assert.rejects(() => create(), /temporarily paused/)
  assert.equal((await create(id)).id, id, 'paused support does not break completed-request retries')
  assert.equal((await update(id, 4, 'Follow up while paused', null, customer)).revision, 5)
  await save({ supportEnabled: true }, 2)
  for (let index = 0; index < 9; index++) await create()
  await assert.rejects(() => create(), /Too many requests/)
  await query("insert into admin_notification_reads(actor,notification_key) values('admin@example.test','support:test') on conflict(actor,notification_key) do update set read_at=now()")
  assert.equal((await query("select * from admin_notification_reads where actor='admin@example.test'")).length, 1)
  assert((await query("select * from platform_admin_events where actor='admin@example.test'")).length >= 5)
  console.log('PASS: repeatable setup; private tables and RPC permissions; atomic settings/audit writes; stale revisions; ticket ownership; idempotent tickets and replies; admin-only statuses; user reopening; pause behavior; rate limit; persisted reads and audit events.')
} finally { await db.close() }
