// Execute real migrations/RPCs in isolated PostgreSQL. No live database writes.
import { PGlite } from '@electric-sql/pglite'
import { readFile } from 'node:fs/promises'
import { randomUUID } from 'node:crypto'
import assert from 'node:assert/strict'

const db = new PGlite()
const store = randomUUID(), customer = randomUUID(), other = randomUUID(), pending = randomUUID()
const query = async (sql, params = []) => (await db.query(sql, params)).rows
const rpc = async (name, params) => (await query(`select public.${name}(${params.map((_, i) => `$${i + 1}`).join(',')}) as result`, params))[0].result
const metadata = { role: 'Store Manager', store_id: store, store_review: { status: 'Approved', application: { storeName: 'Transaction Shop' } } }
const action = (name, revision, status) => rpc('admin_store_action', [store, name, 'Administrative review', 'admin@example.test', revision, status])
try {
  await db.exec("create schema auth; create table auth.users(id uuid primary key,raw_app_meta_data jsonb default '{}',raw_user_meta_data jsonb default '{}',updated_at timestamptz); create role anon; create role authenticated; create role service_role bypassrls;")
  const setup = await readFile(new URL('./setup_database.sql', import.meta.url), 'utf8')
  for (let run = 0; run < 2; run++) {
    const results = await db.exec(setup)
    assert.equal(results.at(-1).rows.length, 26)
    assert(results.at(-1).rows.every(row => row.installed_table))
  }
  for (const id of [store, customer, other, pending]) await query('insert into auth.users(id,raw_app_meta_data) values($1,$2)', [id, id === store ? metadata : {}])
  await query("update auth.users set raw_user_meta_data=$2 where id=$1", [pending, { store_application: { storeName: 'Pending Shop' } }])
  const insert = (owner, sku, status = 'Active') => query("insert into public.store_products(store_id,name,sku,category,condition,price,stock,status,images,payment_options,swap,layaway) values($1,'Phone',$2,'Phones','New',1000,10,$3,'[{}]','{}','{}','{}') returning *", [owner, sku, status])
  const [product] = await insert(store, 'SKU-1')
  await insert(store, 'SKU-2', 'Draft')
  const [otherProduct] = await insert(other, 'OTHER')
  const submit = async kind => rpc('submit_customer_application', [{ reference: randomUUID(), request_id: randomUUID(), customer_id: customer, store_id: store, product_id: product.id, kind, details: {}, snapshot: { price: 1000 }, terms: { months: 3 }, total: 1000, deposit: 100 }, (await query('select revision from store_products where id=$1', [product.id]))[0].revision])
  const act = (a, verb, data = {}, asCustomer = false) => rpc('act_on_customer_application', [a.id, asCustomer ? customer : store, asCustomer, asCustomer ? customer : store, a.revision, verb, data])
  const plan = (await query("insert into subscription_plans(name,amount_minor,duration_days) values('Fixture',10000,30) returning id"))[0].id
  const ref='SUB-'+randomUUID().replaceAll('-','')
  await query("insert into subscription_orders(reference,store_id,plan_id,plan_name,amount_minor,duration_days,email,environment) values($1,$2,$3,'Fixture',10000,30,'owner@example.test','test')",[ref,store,plan])
  await rpc('activate_store_subscription',[ref,'fixture-payment',10000,'GHS','owner@example.test','test',new Date().toISOString()])
  await db.exec('set role service_role')
  let paid = await submit('hire_purchase')
  paid = await act(paid, 'approve')
  paid = await act(paid, 'payment', { amount: 100, method: 'Cash', reference: 'RECEIPT-1', request_id: randomUUID() })
  let unpaid = await submit('layaway')
  unpaid = await act(unpaid, 'approve')
  let offered = await submit('swap')
  offered = await act(offered, 'offer', { credit: 50, reason: 'Trade-in offer' })

  await db.exec('set role authenticated')
  await assert.rejects(() => action('delete', 0, 'Approved'), /permission denied/)
  await assert.rejects(() => action('restore', 0, 'Deleted'), /permission denied/)
  await assert.rejects(() => query('select * from deleted_stores'), /permission denied/)
  await db.exec('set role service_role')
  await assert.rejects(() => action('suspend', 1, 'Approved'), /Store changed/)
  await action('suspend', 0, 'Approved')
  await assert.rejects(() => submit('hire_purchase'), /suspended or deleted/)
  await assert.rejects(() => act(offered, 'accept', {}, true), /suspended or deleted/)
  await assert.rejects(() => insert(store, 'BLOCKED'), /suspended or deleted/)
  await assert.rejects(() => query("update store_products set name='Changed' where id=$1", [product.id]), /suspended or deleted/)
  await assert.rejects(() => act(paid, 'payment', { amount: 10, method: 'Cash', reference: 'BLOCKED', request_id: randomUUID() }), /suspended or deleted/)
  assert.equal((await query('select * from application_payments')).length, 1, 'failed payment rolls back its receipt')
  await action('reactivate', 1, 'Suspended')
  await action('suspend', 2, 'Approved')
  await db.exec('reset role')
  await assert.rejects(() => query('update auth.users set raw_app_meta_data=$2 where id=$1', [store, metadata]), /Store changed/)
  // Force failure halfway through deletion; both archive collections must roll back.
  await db.exec("create function public.test_archive_failure() returns trigger language plpgsql as $$ begin if new.status='Archived' then raise exception 'test forced failure'; end if; return new; end $$; create trigger test_archive_failure before update on store_products for each row execute function public.test_archive_failure();")
  await db.exec('set role service_role')
  await assert.rejects(() => action('delete', 3, 'Suspended'), /test forced failure/)
  assert.equal((await query('select * from deleted_stores')).length, 0)
  assert.equal((await query('select * from deleted_store_products')).length, 0)
  await db.exec('reset role; drop trigger test_archive_failure on store_products; set role service_role;')
  await action('delete', 3, 'Suspended')
  assert.equal((await query('select * from deleted_stores')).length, 1)
  const archived = await query('select * from deleted_store_products')
  assert.equal(archived.length, 2)
  assert.deepEqual(archived.map(row => row.product.status).sort(), ['Active', 'Draft'])
  assert((await query('select status from store_products where store_id=$1', [store])).every(row => row.status === 'Archived'))
  assert.equal((await query('select status from store_products where id=$1', [otherProduct.id]))[0].status, 'Active')
  assert.equal((await query('select * from customer_applications')).length, 3)
  assert.equal((await query('select * from application_payments')).length, 1)
  assert.equal((await query('select * from store_admin_events')).length, 4)
  await assert.rejects(() => action('delete', 3, 'Suspended'), /Store changed/)
  await assert.rejects(() => action('reactivate', 4, 'Deleted'), /not available/)
  await assert.rejects(() => query("update store_products set status='Active' where id=$1", [product.id]), /suspended or deleted/)
  unpaid = await act(unpaid, 'cancel', {}, true)
  assert.equal(unpaid.status, 'Cancelled', 'customers can cancel unpaid plans after archival')
  await assert.rejects(() => act(paid, 'cancel', {}, true), /Only unpaid/)
  await rpc('admin_store_action', [pending, 'delete', 'Rejected business request', 'admin@example.test', 0, 'Pending Approval'])
  assert.equal((await query('select * from deleted_stores')).length, 2)
  await assert.rejects(() => rpc('admin_store_action', [customer, 'delete', 'Not a store', 'admin@example.test', 0, 'Pending Approval']), /Store not found/)
  const stockAfterCancellation = (await query('select stock from store_products where id=$1', [product.id]))[0].stock
  // A failure restoring any product must roll back metadata and preserve both archives.
  await db.exec("reset role; create function public.test_restore_failure() returns trigger language plpgsql as $$ begin if new.status='Active' then raise exception 'test restore failure'; end if; return new; end $$; create trigger test_restore_failure before update on store_products for each row execute function public.test_restore_failure(); set role service_role;")
  await assert.rejects(() => action('restore', 4, 'Deleted'), /test restore failure/)
  assert.equal((await query('select * from deleted_stores')).length, 2)
  assert.equal((await query('select * from deleted_store_products')).length, 2)
  await db.exec('reset role')
  assert.equal((await query("select raw_app_meta_data->'store_review'->>'status' as status from auth.users where id=$1", [store]))[0].status, 'Deleted')
  await db.exec('drop trigger test_restore_failure on store_products; set role service_role;')
  await assert.rejects(() => action('restore', 3, 'Deleted'), /Store changed/)
  assert.deepEqual(await action('restore', 4, 'Deleted'), {status:'Suspended',revision:5})
  assert.deepEqual((await query('select status from store_products where store_id=$1', [store])).map(p => p.status).sort(), ['Active','Draft'])
  assert.equal((await query('select stock from store_products where id=$1', [product.id]))[0].stock, stockAfterCancellation)
  assert.equal((await query('select * from deleted_store_products')).length, 0)
  assert.equal((await query('select * from deleted_stores')).length, 1)
  await assert.rejects(() => insert(store, 'STILL-SUSPENDED'), /suspended or deleted/)
  await assert.rejects(() => action('restore', 5, 'Suspended'), /not available/)
  await action('reactivate', 5, 'Suspended')
  // Restored stores can be deleted again; each lifecycle event is retained.
  await action('delete', 6, 'Approved')
  assert.deepEqual(await action('restore', 7, 'Deleted'), {status:'Approved',revision:8})
  assert.equal((await query('select * from store_admin_events where store_id=$1', [store])).length, 8)
  assert.equal((await query('select * from customer_applications')).length, 3)
  assert.equal((await query('select * from application_payments')).length, 1)
  assert.equal((await query('select status from store_products where id=$1', [otherProduct.id]))[0].status, 'Active')
  assert.deepEqual(await rpc('admin_store_action', [pending, 'restore', 'Restore pending request', 'admin@example.test', 1, 'Deleted']), {status:'Pending Approval',revision:2})
  await db.exec('reset role')
  await query("update auth.users set raw_app_meta_data=jsonb_set(raw_app_meta_data,'{store_review,status}','\"Rejected\"') where id=$1", [pending])
  await db.exec('set role service_role')
  await rpc('admin_store_action', [pending, 'delete', 'Archive rejected request', 'admin@example.test', 2, 'Rejected'])
  assert.deepEqual(await rpc('admin_store_action', [pending, 'restore', 'Restore rejected request', 'admin@example.test', 3, 'Deleted']), {status:'Rejected',revision:4})
  assert.equal((await query('select * from deleted_stores')).length, 0)
  console.log('PASS: repeatable setup; admin-only lifecycle RPCs; stale actions; atomic delete/restore rollback; restored statuses; preserved stock and purchases; suspension retained; pending/rejected restoration; repeat deletion; audit history.')
} finally { await db.close() }
